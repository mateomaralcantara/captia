export const dictionaries: Record<Lang, Dictionary> = { es, en };

export function resolveLang(value: string | undefined): Lang {
  return value === "en" ? "en" : "es";
}

export function errorMessage(t: Dictionary, code: string | undefined): string {
  if (code && code in t.errors) return t.errors[code as keyof Dictionary["errors"]];
  return t.errors.generic;
}
